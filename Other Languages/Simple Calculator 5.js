const symb = prompt("Symbol? ");
const fir = Number(prompt("First Number? "));
const sec = Number(prompt("Second Number? "));

if (symb === '+') {
console.log("Results:", fir + sec);
}

if (symb === '-') {
console.log("Results:", fir - sec);
}

if (symb === '*') {
console.log("Results:", fir * sec);
}

if (symb === '/') {
console.log("Results:", fir / sec);
}
